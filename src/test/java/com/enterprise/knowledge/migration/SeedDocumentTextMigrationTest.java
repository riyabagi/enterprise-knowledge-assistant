package com.enterprise.knowledge.migration;

import org.flywaydb.core.Flyway;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class SeedDocumentTextMigrationTest {

    private static final List<String> FILENAMES = List.of(
            "remote-work-policy.txt",
            "it-security-guidelines.txt",
            "onboarding-handbook.txt",
            "salary-bands-confidential.txt",
            "q3-it-infra-report.txt");

    @Test
    void migrationBuildsSeedTextFromOrderedChunksWithoutCreatingVersionsOrChunks() throws Exception {
        JdbcDataSource dataSource = createDatabase();
        seedDocuments(dataSource, false);

        migrate(dataSource, "3");

        assertEquals(
                "Demonstration text assembled from the seeded searchable passages. "
                        + "This is not the original source file.\n\n"
                        + "Section zero\nFirst passage\n\nSection one\nSecond passage",
                extractedText(dataSource, 1));
        for (long id = 2; id <= 5; id++) {
            assertTrue(extractedText(dataSource, id).contains("Passage for document " + id));
        }
        assertEquals("Uploaded document text", extractedText(dataSource, 6));
        assertEquals(6, rowCount(dataSource, "document_version"));
        assertEquals(6, rowCount(dataSource, "knowledge_chunk"));

        migrate(dataSource, "3");

        assertEquals(6, rowCount(dataSource, "document_version"));
        assertEquals(6, rowCount(dataSource, "knowledge_chunk"));
        assertTrue(extractedText(dataSource, 5).contains("Passage for document 5"));
    }

    @Test
    void migrationPreservesAlreadyPopulatedSeedText() throws Exception {
        JdbcDataSource dataSource = createDatabase();
        seedDocuments(dataSource, true);

        migrate(dataSource, "3");

        assertEquals("User-maintained text", extractedText(dataSource, 1));
        assertTrue(extractedText(dataSource, 2).contains("Passage for document 2"));
    }

    private JdbcDataSource createDatabase() throws Exception {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:seed-text-" + UUID.randomUUID()
                + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        dataSource.setPassword("");
        try (Connection connection = dataSource.getConnection();
                PreparedStatement versionTable = connection.prepareStatement("""
                        CREATE TABLE document_version (
                            id BIGINT PRIMARY KEY,
                            document_id BIGINT NOT NULL,
                            version_number INT NOT NULL,
                            original_filename VARCHAR(500) NOT NULL,
                            checksum VARCHAR(64) NOT NULL,
                            extracted_text CLOB
                        )
                        """);
                PreparedStatement chunkTable = connection.prepareStatement("""
                        CREATE TABLE knowledge_chunk (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            document_version_id BIGINT NOT NULL,
                            chunk_index INT NOT NULL,
                            section_reference VARCHAR(300),
                            content CLOB NOT NULL
                        )
                        """)) {
            versionTable.execute();
            chunkTable.execute();
        }
        return dataSource;
    }

    private void seedDocuments(JdbcDataSource dataSource, boolean populatedFirstSeed) throws Exception {
        try (Connection connection = dataSource.getConnection()) {
            for (int id = 1; id <= FILENAMES.size(); id++) {
                String sql = """
                        INSERT INTO document_version
                            (id, document_id, version_number, original_filename, checksum, extracted_text)
                        VALUES (?, ?, 1, ?, ?, ?)
                        """;
                try (PreparedStatement insert = connection.prepareStatement(sql)) {
                    insert.setLong(1, id);
                    insert.setLong(2, id);
                    insert.setString(3, FILENAMES.get(id - 1));
                    insert.setString(4, "abc00" + id);
                    insert.setString(5, populatedFirstSeed && id == 1
                            ? "User-maintained text"
                            : null);
                    insert.executeUpdate();
                }
                if (id == 1) {
                    insertChunk(connection, id, 1, "Section one", "Second passage");
                    insertChunk(connection, id, 0, "Section zero", "First passage");
                } else {
                    insertChunk(connection, id, 0, "Section " + id,
                            "Passage for document " + id);
                }
            }
            try (PreparedStatement insert = connection.prepareStatement("""
                    INSERT INTO document_version
                        (id, document_id, version_number, original_filename, checksum, extracted_text)
                    VALUES (6, 6, 1, 'uploaded.txt', 'upload-checksum', 'Uploaded document text')
                    """)) {
                insert.executeUpdate();
            }
        }
    }

    private void insertChunk(
            Connection connection, long versionId, int index, String section, String content)
            throws Exception {
        try (PreparedStatement insert = connection.prepareStatement("""
                INSERT INTO knowledge_chunk
                    (document_version_id, chunk_index, section_reference, content)
                VALUES (?, ?, ?, ?)
                """)) {
            insert.setLong(1, versionId);
            insert.setInt(2, index);
            insert.setString(3, section);
            insert.setString(4, content);
            insert.executeUpdate();
        }
    }

    private void migrate(JdbcDataSource dataSource, String baselineVersion) {
        Flyway.configure()
                .dataSource(dataSource)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion(baselineVersion)
                .load()
                .migrate();
    }

    private String extractedText(JdbcDataSource dataSource, long id) throws Exception {
        try (Connection connection = dataSource.getConnection();
                PreparedStatement query = connection.prepareStatement(
                        "SELECT extracted_text FROM document_version WHERE id = ?")) {
            query.setLong(1, id);
            try (ResultSet result = query.executeQuery()) {
                if (!result.next()) {
                    throw new IllegalStateException("Missing version fixture: " + id);
                }
                return result.getString(1);
            }
        }
    }

    private int rowCount(JdbcDataSource dataSource, String table) throws Exception {
        try (Connection connection = dataSource.getConnection();
                PreparedStatement query = connection.prepareStatement(
                        "SELECT COUNT(*) FROM " + table);
                ResultSet result = query.executeQuery()) {
            result.next();
            return result.getInt(1);
        }
    }
}
